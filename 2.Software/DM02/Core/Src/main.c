static void CAN2_Bare_Test_Init(void)
{
  /* MX_FDCAN2_Init() 已完成消息 RAM 和 1 Mbps 位时序配置，这里只启动外设。 */
  can2_bare_start_status = (uint32_t)HAL_FDCAN_Start(&hfdcan2);
  can2_bare_hal_error_code = hfdcan2.ErrorCode;
}

static void CAN2_Bare_Test_Send(void)
{
  FDCAN_TxHeaderTypeDef header = {0};
  FDCAN_ProtocolStatusTypeDef protocol = {0};
  FDCAN_ErrorCountersTypeDef counters = {0};
  static uint32_t sequence = 0U;
  uint8_t data[8];

  sequence++;
  can2_bare_loop_count++;
  data[0] = 'C';
  data[1] = 'A';
  data[2] = 'N';
  data[3] = '2';
  data[4] = (uint8_t)(sequence >> 24);
  data[5] = (uint8_t)(sequence >> 16);
  data[6] = (uint8_t)(sequence >> 8);
  data[7] = (uint8_t)sequence;

  header.Identifier = 0x124U;
  header.IdType = FDCAN_STANDARD_ID;
  header.TxFrameType = FDCAN_DATA_FRAME;
  header.DataLength = FDCAN_DLC_BYTES_8;
  header.ErrorStateIndicator = FDCAN_ESI_ACTIVE;
  header.BitRateSwitch = FDCAN_BRS_OFF;
  header.FDFormat = FDCAN_CLASSIC_CAN;
  header.TxEventFifoControl = FDCAN_NO_TX_EVENTS;
  header.MessageMarker = 0U;

  can2_bare_tx_attempt_count++;
  if (HAL_FDCAN_AddMessageToTxFifoQ(&hfdcan2, &header, data) == HAL_OK) {
    can2_bare_tx_ok_count++;
  } else {
    can2_bare_tx_error_count++;
  }

  can2_bare_hal_error_code = hfdcan2.ErrorCode;
  can2_bare_tx_fifo_free = HAL_FDCAN_GetTxFifoFreeLevel(&hfdcan2);
  if (HAL_FDCAN_GetProtocolStatus(&hfdcan2, &protocol) == HAL_OK) {
    can2_bare_last_error_code = protocol.LastErrorCode;
    can2_bare_bus_off = protocol.BusOff;
  }
  if (HAL_FDCAN_GetErrorCounters(&hfdcan2, &counters) == HAL_OK) {
    can2_bare_tx_error_counter = counters.TxErrorCnt;
  }
}

